/// Liefert die Glyphe eines Bytes; unbekannte Zeichen werden zu `?`.
#[inline]
pub fn glyph(b: u8) -> &'static [u8; GLYPH_H] {
    if b >= FIRST && b <= LAST {
        &GLYPHS[(b - FIRST) as usize]
    } else {
        &GLYPHS[(b'?' - FIRST) as usize]
    }
}
